test.describe('touch orientation', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 844 } })
  test('touch rotation commits on release, cancels safely, and respects the lock', async ({ page }) => {
    await page.goto('/')
    const dial = page.getByTestId('canvas-compass'), rose = dial.locator('svg')
    const toggle = page.getByRole('switch', { name: '自由调整朝向' })
    await toggle.setChecked(true)
    const session = await page.context().newCDPSession(page)
    const a = await compassPoint(page, 0), b = await compassPoint(page, 90)
    const touch = async (type: 'touchStart' | 'touchMove' | 'touchEnd' | 'touchCancel', point?: { x: number; y: number }) => {
      await session.send('Input.dispatchTouchEvent', { type, touchPoints: point ? [{ ...point, id: 1 }] : [] })
    }
    await touch('touchStart', a); await touch('touchMove', b)
    await expect(rose).toHaveAttribute('data-north-angle', '90')
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('roomly.plan.v1') ?? '{}').northAngle ?? 0)).toBe(0)
    await touch('touchCancel')
    await expect(rose).toHaveAttribute('data-north-angle', '0')
    await touch('touchStart', a); await touch('touchMove', b); await touch('touchEnd')
    await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('roomly.plan.v1') ?? '{}').northAngle)).toBe(90)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await toggle.setChecked(false)
    await touch('touchStart', a); await touch('touchMove', b); await touch('touchEnd')
    await expect(rose).toHaveAttribute('data-north-angle', '90')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.screenshot({ path: 'work/roomly-orientation-locked-mobile.png', fullPage: true })
    await session.detach()
  })
})
