async function compassPoint(page: Page, degrees: number) {
  const box = await page.getByTestId('canvas-compass').locator('svg').boundingBox()
  if (!box) throw new Error('Compass is not visible')
  const radians = degrees * Math.PI / 180, radius = box.width * .32
  return { x: box.x + box.width / 2 + Math.sin(radians) * radius, y: box.y + box.height / 2 - Math.cos(radians) * radius }
}

async function rotateCompass(page: Page, from: number, to: number) {
  const a = await compassPoint(page, from), b = await compassPoint(page, to)
  await page.mouse.move(a.x, a.y); await page.mouse.down()
  await page.mouse.move(b.x, b.y, { steps: 8 }); await page.mouse.up()
}

