async function loadPlan(page: Page, plan: Plan) {
  await page.addInitScript(p => localStorage.setItem('roomly.plan.v1', JSON.stringify(p)), plan)
  await page.goto('/')
}
async function point(page: Page, x: number, y: number) {
  return page.locator('.floor-canvas').evaluate((el, p) => {
    const svg = el as SVGSVGElement, v = new DOMPoint(p.x, p.y).matrixTransform(svg.getScreenCTM()!)
    return { x: v.x, y: v.y }
  }, { x, y })
}
async function drag(page: Page, a: { x: number; y: number }, b: { x: number; y: number }) {
  const from = await point(page, a.x, a.y), to = await point(page, b.x, b.y)
  await page.mouse.move(from.x, from.y); await page.mouse.down(); await page.mouse.move(to.x, to.y, { steps: 12 }); await page.mouse.up()
}
